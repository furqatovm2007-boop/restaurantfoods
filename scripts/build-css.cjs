// Joins the main site's stylesheets, in their cascade order, into one minified public/app.css.
// One render-blocking request instead of eleven (PageSpeed: "Render-blocking requests").
// Run after editing any of these files: node scripts/build-css.cjs  (tests/app-css.test.cjs checks it is fresh).
const fs = require('fs'),
  path = require('path'),
  // esbuild comes with Vite (no extra dependency).
  esbuild = require(require.resolve('esbuild', { paths: [path.dirname(require.resolve('vite/package.json'))] }));
const FILES = ['restaurant', 'call-ai', 'otp-glass', 'menu-book', 'ai-chat', 'welcome-guide', 'demo-room', 'premium', 'motion', 'glass', 'auth', 'mvp'];
function build() {
  const joined = FILES.map((f) => `/* ${f}.css */\n` + fs.readFileSync(path.join('public', f + '.css'), 'utf8')).join('\n');
  // No syntax lowering: the browsers that run the site read the CSS as written.
  return '/* Generated by scripts/build-css.cjs from ' + FILES.map((f) => f + '.css').join(', ') + '. Edit those files. */\n' + esbuild.transformSync(joined, { loader: 'css', minify: true, target: 'esnext' }).code;
}
module.exports = { FILES, build };
if (require.main === module) {
  const out = build();
  fs.writeFileSync('public/app.css', out);
  console.log('public/app.css', out.length, 'bytes');
}
